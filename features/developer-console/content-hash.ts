/*
 * Browser-side content hash for the mock adapter.
 *
 * The Registry's real hash is features/registry/canonical.ts (RFC 8785 + SHA-256), which
 * imports node:crypto and cannot ship to the browser. For the plain JSON the console
 * produces (objects, arrays, strings, finite numbers, booleans, null) RFC 8785 reduces to:
 * keys sorted by UTF-16 code units, primitives serialized as ECMAScript JSON, no
 * whitespace. content-hash.test.ts checks this file against hashSnapshot() byte for byte.
 *
 * This is not a replacement for the server: it does not reject lone surrogates, duplicate
 * keys or oversize input. The real adapter never hashes in the browser; it sends the
 * server-returned hash back as expectedContentHash.
 */

export function canonicalJson(value: unknown): string {
  if (value === null || typeof value === "boolean" || typeof value === "string") return JSON.stringify(value);
  if (typeof value === "number") {
    if (!Number.isFinite(value)) throw new TypeError("Non-finite number");
    return JSON.stringify(value);
  }
  if (Array.isArray(value)) return `[${value.map(canonicalJson).join(",")}]`;
  if (typeof value === "object") {
    const record = value as Record<string, unknown>;
    const keys = Object.keys(record).filter((key) => record[key] !== undefined).sort();
    return `{${keys.map((key) => `${JSON.stringify(key)}:${canonicalJson(record[key])}`).join(",")}}`;
  }
  throw new TypeError(`Unsupported JSON value: ${typeof value}`);
}

